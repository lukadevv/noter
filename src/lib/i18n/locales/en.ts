/**
 * The English catalogue, and the source of truth for the message shape.
 *
 * Every other locale is typed against this object, so a missing or misspelled
 * key is a compile error rather than a blank label at runtime. Counted messages
 * use plural forms keyed by `Intl.PluralRules` categories; English needs `one`
 * and `other`, while Arabic needs six and Chinese needs one.
 */
import type { PluralForms } from '../types'

